import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const sourceOnly = process.argv.includes('--source-only')
const packageJson = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const playgroundPackage = JSON.parse(readFileSync(resolve(root, 'playground/package.json'), 'utf8'))
const rootConfig = readFileSync(resolve(root, 'eslint.config.mjs'), 'utf8')
const playgroundConfig = readFileSync(resolve(root, 'playground/eslint.config.js'), 'utf8')
const playgroundNuxtConfig = readFileSync(resolve(root, 'playground/nuxt.config.ts'), 'utf8')
const rootLock = readFileSync(resolve(root, 'bun.lock'), 'utf8')
const playgroundLock = readFileSync(resolve(root, 'playground/bun.lock'), 'utf8')

const problems = []


function requireLegacyProviderPolicyParity(scope, text) {
  if (!text.includes("'ts/method-signature-style': ['error', 'method']"))
    problems.push(`${scope} must preserve the former wrapper method-signature policy while using official providers`)
  if (!text.includes("'no-console': 'off'"))
    problems.push(`${scope} must preserve the former wrapper no-console policy while using official providers`)
  if (!text.includes("'style/max-len': ['warn'"))
    problems.push(`${scope} must preserve the former wrapper max-len warning contract while using official providers`)
}

function forbidGabortormaProvider(scope, text) {
  if (text.includes('@gabortorma/antfu-eslint-config'))
    problems.push(`${scope} still references @gabortorma/antfu-eslint-config`)
  if (text.includes('@gabortorma/nuxt-eslint-layer'))
    problems.push(`${scope} still references @gabortorma/nuxt-eslint-layer`)
}

if (packageJson.devDependencies?.['@antfu/eslint-config'] !== '3.7.1')
  problems.push('root devDependency @antfu/eslint-config must remain pinned to 3.7.1 during the provider-only migration')
if (packageJson.devDependencies?.['@nuxt/eslint'] !== '1.7.0')
  problems.push('root devDependency @nuxt/eslint must be pinned to the previously transitive official baseline 1.7.0')
if (packageJson.devDependencies?.['@gabortorma/antfu-eslint-config'] || packageJson.devDependencies?.['@gabortorma/nuxt-eslint-layer'])
  problems.push('root package.json must not depend on the removed Gabortorma ESLint provider/layer')

if (playgroundPackage.devDependencies?.['@antfu/eslint-config'] !== '4.18.0')
  problems.push('playground must pin @antfu/eslint-config to 4.18.0, matching the former layer effective baseline')
if (playgroundPackage.devDependencies?.['@nuxt/eslint'] !== '1.7.0')
  problems.push('playground must depend directly on official @nuxt/eslint@1.7.0')
if (playgroundPackage.devDependencies?.eslint !== '9.31.0')
  problems.push('playground must pin eslint to 9.31.0, matching the former layer effective baseline')
if (playgroundPackage.devDependencies?.['@gabortorma/antfu-eslint-config'] || playgroundPackage.devDependencies?.['@gabortorma/nuxt-eslint-layer'])
  problems.push('playground package.json must not depend on the removed Gabortorma ESLint provider/layer')

if (!rootConfig.includes("from '@antfu/eslint-config'"))
  problems.push('root ESLint config must import @antfu/eslint-config directly')
if (!playgroundConfig.includes("from '@antfu/eslint-config'"))
  problems.push('playground ESLint config must import @antfu/eslint-config directly')
if (!playgroundConfig.includes("from './.nuxt/eslint.config.mjs'"))
  problems.push('playground ESLint config must compose the project-aware config generated by @nuxt/eslint')
requireLegacyProviderPolicyParity('root ESLint config', rootConfig)
requireLegacyProviderPolicyParity('playground ESLint config', playgroundConfig)
if (existsSync(resolve(root, 'playground/eslint.config.mjs')))
  problems.push('playground must keep a single canonical eslint.config.js; remove the stale duplicate eslint.config.mjs')

if (!playgroundNuxtConfig.includes("'@nuxt/eslint'"))
  problems.push('playground Nuxt modules must include official @nuxt/eslint')
if (/extends\s*:\s*\[[^\]]*@gabortorma\/nuxt-eslint-layer/s.test(playgroundNuxtConfig))
  problems.push('playground must not extend @gabortorma/nuxt-eslint-layer')
if (!/eslint\s*:\s*\{[\s\S]*?checker\s*:\s*false[\s\S]*?standalone\s*:\s*false[\s\S]*?\}/m.test(playgroundNuxtConfig))
  problems.push('playground @nuxt/eslint must disable the dev checker and standalone base rules when composing Antfu')
if (!/autoInit\s*:\s*false/.test(playgroundNuxtConfig))
  problems.push('playground @nuxt/eslint autoInit must be disabled because eslint.config.js is maintained explicitly')

for (const [scope, text] of [
  ['root package/config', `${JSON.stringify(packageJson)}\n${rootConfig}`],
  ['playground package/config', `${JSON.stringify(playgroundPackage)}\n${playgroundConfig}\n${playgroundNuxtConfig}`],
]) {
  forbidGabortormaProvider(scope, text)
}

if (!sourceOnly) {
  forbidGabortormaProvider('root bun.lock', rootLock)
  forbidGabortormaProvider('playground bun.lock', playgroundLock)
}

if (!sourceOnly) {
  if (!rootLock.includes('"@antfu/eslint-config": "3.7.1"'))
    problems.push('root bun.lock workspace must pin @antfu/eslint-config to 3.7.1')
  if (!rootLock.includes('"@nuxt/eslint": "1.7.0"'))
    problems.push('root bun.lock workspace must pin @nuxt/eslint to 1.7.0')
  if (!/^    "@nuxt\/eslint": \["@nuxt\/eslint@1\.7\.0"/m.test(rootLock))
    problems.push('root bun.lock must resolve official @nuxt/eslint@1.7.0')

  if (!playgroundLock.includes('"@antfu/eslint-config": "4.18.0"'))
    problems.push('playground bun.lock workspace must pin @antfu/eslint-config to 4.18.0')
  if (!playgroundLock.includes('"@nuxt/eslint": "1.7.0"'))
    problems.push('playground bun.lock workspace must pin @nuxt/eslint to 1.7.0')
  if (!playgroundLock.includes('"eslint": "9.31.0"'))
    problems.push('playground bun.lock workspace must pin eslint to 9.31.0')
  if (!/^    "@nuxt\/eslint": \["@nuxt\/eslint@1\.7\.0"/m.test(playgroundLock))
    problems.push('playground bun.lock must resolve official @nuxt/eslint@1.7.0')
}

if (problems.length) {
  console.error('[nuxt-feathers-zod] Official ESLint provider migration policy failed:')
  for (const problem of problems)
    console.error(`- ${problem}`)
  console.error('[nuxt-feathers-zod] If manifests/configs are already migrated, run `bun run eslint:official:sync-locks` with Bun 1.3.14 to canonicalize both lockfiles.')
  process.exit(1)
}

console.log(sourceOnly
  ? '[nuxt-feathers-zod] Official ESLint provider source migration is coherent; lockfile canonicalization is intentionally pending.'
  : '[nuxt-feathers-zod] Official ESLint provider migration is complete: direct Antfu presets + @nuxt/eslint@1.7.0, no Gabortorma wrapper/layer, canonical locks, legacy lint policy parity preserved explicitly.')
