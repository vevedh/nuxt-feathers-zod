import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(process.cwd())
const read = relative => readFileSync(resolve(root, relative), 'utf8')
const packageJson = JSON.parse(read('package.json'))
const bunLock = read('bun.lock')
const starterConfig = read('examples/nfz-quasar-unocss-pinia-starter/nuxt.config.ts')
const starterE2e = read('examples/nfz-quasar-unocss-pinia-starter/scripts/e2e-ci.mjs')
const starterRelease = read('scripts/validate-starter-release.mjs')
const starterRuntimePaths = read('examples/nfz-quasar-unocss-pinia-starter/scripts/runtime-paths.mjs')
const starterRuntimeEvidence = read('examples/nfz-quasar-unocss-pinia-starter/scripts/runtime-evidence.mjs')
const starterRuntimePathsTest = read('test/unit/starter-release-runtime-paths.test.ts')
const starterRuntimeEvidenceTest = read('test/unit/starter-release-runtime-evidence.test.ts')
const starterMongo = read('scripts/lib/starter-release-mongodb.mjs')
const starterMongoTest = read('test/unit/starter-release-mongodb.test.ts')
const windowsVerifier = read('scripts/verify-windows.ps1')
const problems = []

function requireText(source, expected, label) {
  if (!source.includes(expected))
    problems.push(`${label}: missing ${JSON.stringify(expected)}`)
}

requireText(starterE2e, "import { randomBytes } from 'node:crypto'", 'ephemeral release auth secret source')
requireText(starterE2e, "const authSecret = randomBytes(48).toString('base64url')", 'strong ephemeral release auth secret')
requireText(starterE2e, 'NFZ_AUTH_SECRET: authSecret', 'production server auth secret injection')
requireText(starterE2e, "import { assertStarterRuntimeProcessHealthy } from './runtime-evidence.mjs'", 'runtime process evidence helper import')
requireText(starterE2e, 'exitCode: child.exitCode', 'starter process exit evidence')
requireText(starterE2e, 'signalCode: child.signalCode', 'starter process signal evidence')
requireText(starterE2e, 'let child', 'starter child declaration before readiness helper')
requireText(starterE2e, "child = spawn(process.execPath, ['.output/server/index.mjs']", 'starter child process assignment')
requireText(starterRuntimeEvidence, "captured.includes('status=failed')", 'fail-fast bootstrap failure evidence')
requireText(starterRuntimeEvidence, 'exitCode !== null || signalCode !== null', 'premature process termination evidence')
requireText(starterRuntimeEvidenceTest, 'accepts an alive runtime without an optional ready diagnostic line', 'optional ready diagnostic regression test')
requireText(starterRuntimeEvidenceTest, 'rejects an explicit bootstrap failure', 'bootstrap failure evidence regression test')
requireText(starterRuntimeEvidenceTest, 'rejects a server process that exited before validation completed', 'process exit evidence regression test')
requireText(starterE2e, "import { resolveMountedRoutePath } from './runtime-paths.mjs'", 'mounted route resolver import')
requireText(starterE2e, "const restMountPath = process.env.NFZ_E2E_REST_PATH || '/feathers'", 'starter REST mount path')
requireText(starterE2e, "const configuredHealthPath = process.env.NFZ_E2E_HEALTH_PATH || '/api/health'", 'configured starter health path')
requireText(starterE2e, 'const healthPath = resolveMountedRoutePath(restMountPath, configuredHealthPath)', 'effective health route resolution')
requireText(starterE2e, 'const result = await request(healthPath)', 'starter readiness probe')
requireText(starterE2e, 'const health = await request(healthPath)', 'starter health assertion')
requireText(starterConfig, "path: '/feathers'", 'configured starter REST mount')
requireText(starterConfig, "options: { path: '/api/health'", 'configured internal health endpoint')
requireText(starterRuntimePaths, 'export function resolveMountedRoutePath', 'starter mounted route helper')
requireText(starterRuntimePathsTest, "expect(resolveMountedRoutePath('/feathers', '/api/health')).toBe('/feathers/api/health')", 'mounted health route regression test')
requireText(starterRelease, "import { provisionStarterReleaseMongo } from './lib/starter-release-mongodb.mjs'", 'starter MongoDB provisioner import')
requireText(starterRelease, 'mongoRuntime = await provisionStarterReleaseMongo()', 'starter MongoDB runtime provisioning')
requireText(starterRelease, 'MONGODB_URL: mongoRuntime.url', 'resolved starter MongoDB URL injection')
requireText(starterRelease, 'await mongoRuntime?.stop()', 'starter MongoDB cleanup')
requireText(starterRelease, "['prepare', 'typecheck', 'build', 'runtime:doctor', 'e2e:ci']", 'exact candidate production lifecycle')
requireText(starterMongo, "const MODES = new Set(['auto', 'external', 'memory'])", 'starter MongoDB validation modes')
requireText(starterMongo, 'await probe(normalizedUrl)', 'external MongoDB reachability probe')
requireText(starterMongo, "await import('mongodb-memory-server')", 'isolated MongoDB runtime loader')
requireText(starterMongo, "instance: { dbName: 'nfz_starter_release' }", 'isolated starter release database')
requireText(starterMongo, 'await server.stop()', 'isolated MongoDB shutdown')
requireText(starterMongoTest, 'falls back to an isolated runtime when the configured URL is unreachable', 'MongoDB fallback regression test')
requireText(windowsVerifier, "Import-ReleaseEnvironmentFile -Path (Join-Path (Get-Location) '.env.release.local')", 'optional release environment loader')

if ((starterE2e.match(/assertStarterRuntimeProcessHealthy\(/g) || []).length < 2)
  problems.push('starter release E2E must verify process health during readiness polling and after all observable production checks')
if (starterE2e.indexOf('let child') > starterE2e.indexOf('async function waitForServer'))
  problems.push('starter child process must be declared before the readiness helper to satisfy lint and make process evidence explicit')
if (starterE2e.includes('const child = spawn('))
  problems.push('starter child process must be assigned to the predeclared binding instead of being referenced before declaration')
if (starterE2e.includes('nfzReadyLines') || starterE2e.includes('expected one embedded runtime ready transition'))
  problems.push('starter release E2E must not treat optional status=ready console diagnostics as release evidence')
if (starterE2e.includes("NFZ_BOOTSTRAP_DIAGNOSTICS: 'true'"))
  problems.push('starter release E2E must not pretend a runtime-only environment variable can change build-time Nuxt bootstrap diagnostics')
if (packageJson.devDependencies?.['mongodb-memory-server'] !== '10.4.3')
  problems.push('mongodb-memory-server must remain an explicit pinned development dependency for isolated starter validation')
if (!bunLock.includes('"mongodb-memory-server": "10.4.3"'))
  problems.push('bun.lock must retain the direct mongodb-memory-server development dependency')
if (starterE2e.indexOf('...process.env') > starterE2e.indexOf('NFZ_AUTH_SECRET: authSecret'))
  problems.push('starter release E2E must override inherited authentication secrets after spreading the parent environment')
if (/NFZ_AUTH_SECRET\s*:\s*['"][^'"]+['"]/.test(starterE2e))
  problems.push('starter release E2E must not contain a hard-coded authentication secret')
if (/console\.(?:log|warn|error)\([^\n]*(?:authSecret|NFZ_AUTH_SECRET)/.test(starterE2e))
  problems.push('starter release E2E must not print authentication key material')
if (starterE2e.includes("request('/api/health')"))
  problems.push('starter release E2E must probe the externally mounted Express route, not the unmounted internal module path')
if (starterRelease.includes("if (!process.env.MONGODB_URL)"))
  problems.push('starter release validation must not require an external MongoDB in auto mode')
if (windowsVerifier.includes('MONGODB_URL is required for -Full'))
  problems.push('the complete Windows release gate must allow isolated MongoDB fallback')

if (problems.length) {
  console.error('[nuxt-feathers-zod] Starter release runtime guard failed:')
  for (const problem of problems)
    console.error(`- ${problem}`)
  process.exit(1)
}

console.log('[nuxt-feathers-zod] Starter production E2E uses observable HTTP/auth/CRUD evidence, process liveness, the mounted health route, ephemeral auth and autonomous MongoDB provisioning.')
